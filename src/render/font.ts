const ROWS: Record<string, number[][]> = {};
for (const [ch, rows] of Object.entries(GLYPHS)) {
  ROWS[ch] = rows.split(' ').map((r) => [...r].map((c, i) => (c === '1' ? i : -1)).filter((i) => i >= 0));
}

export const CHAR_W = 6;
export const CHAR_H = 7;

export function textWidth(text: string, scale = 1): number {
  return text.length * CHAR_W * scale - scale;
}

export type Align = 'left' | 'center' | 'right';

export function drawText(
  ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale = 1,
  align: Align = 'left', shadow: string | null = null,
) {
  text = text.toUpperCase();
  if (align === 'center') x -= Math.floor(textWidth(text, scale) / 2);
  else if (align === 'right') x -= textWidth(text, scale);
  x = Math.round(x);
  y = Math.round(y);
  if (shadow) drawRaw(ctx, text, x + scale, y + scale, shadow, scale);
  drawRaw(ctx, text, x, y, color, scale);
}

function drawRaw(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale: number) {
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const rows = ROWS[text[i]];
    if (!rows) continue;
    const cx = x + i * CHAR_W * scale;
    for (let r = 0; r < 7; r++) for (const c of rows[r]) ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
  }
}
